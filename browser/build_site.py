#!/usr/bin/env python3
"""Build a static site containing only the app, converter, and pinned runtime."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import shutil
import tempfile

from install_runtime import ROOT, VERSION

MARKER = ".bt1-site-build"
APP_FILES = ("index.html", "app.mjs", "ncnr.mjs", "storage.mjs", "compatibility.mjs", "worker.mjs")
RUNTIME_SUFFIXES = {".js", ".mjs", ".wasm", ".json", ".zip", ".whl"}
CONFIG = {
    "runtimeURL": "./pyodide/",
    "packageURL": "./python/bt1modern/",
    "browserPythonURL": "./python/browser/",
    "validationURL": None,
    "testURL": None,
    "evidenceURL": None,
}


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def copy_file(source: Path, destination: Path) -> None:
    if not source.is_file() or source.is_symlink():
        raise ValueError(f"Expected a regular source file: {source}")
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, destination)


def build(destination: Path, runtime: Path) -> dict:
    destination = destination.resolve()
    if destination == ROOT or ROOT.is_relative_to(destination):
        raise ValueError("Site output cannot replace the project or its parent")
    if destination.exists() and not (destination / MARKER).is_file():
        raise ValueError(f"Refusing to replace an unrecognized directory: {destination}")
    provenance_path = runtime.parent / "provenance.json"
    provenance = json.loads(provenance_path.read_text())
    if provenance["pyodide_version"] != VERSION:
        raise ValueError("Installed runtime version does not match the pinned installer")
    lock_path = runtime / "pyodide-lock.json"
    if digest(lock_path) != provenance["lock_sha256"]:
        raise ValueError("Installed Pyodide package lock hash changed")
    for package in provenance["packages"]:
        if digest(runtime / package["file"]) != package["sha256"]:
            raise ValueError(f"Installed package hash changed: {package['name']}")

    destination.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=".bt1-site-", dir=destination.parent))
    try:
        for name in APP_FILES:
            copy_file(ROOT / "browser" / name, staging / name)
        config = "export const CONFIG = Object.freeze(" + json.dumps(CONFIG, indent=2) + ");\n"
        (staging / "runtime-config.mjs").write_text(config)
        for source in sorted((ROOT / "bt1modern").glob("*.py")):
            copy_file(source, staging / "python" / "bt1modern" / source.name)
        copy_file(ROOT / "browser" / "adapter.py", staging / "python" / "browser" / "adapter.py")
        for source in sorted(runtime.iterdir()):
            if source.suffix in RUNTIME_SUFFIXES:
                copy_file(source, staging / "pyodide" / source.name)
        # Jekyll must not alter WebAssembly or Python assets.
        (staging / ".nojekyll").write_text("")
        (staging / MARKER).write_text("Generated by browser/build_site.py\n")
        # Keep public provenance free of local paths, scan data and test reports.
        manifest = {
            "pyodide_version": VERSION,
            "python_version": provenance["lock_info"]["python"],
            "numpy_version": next(p["version"] for p in provenance["packages"] if p["name"] == "numpy"),
            "core_source": {key: provenance["core"][key] for key in ("url", "sha256")},
            "package_sources": [{key: p[key] for key in ("name", "version", "url", "sha256")} for p in provenance["packages"]],
            "files": {str(p.relative_to(staging)): {"sha256": digest(p), "bytes": p.stat().st_size}
                      for p in sorted(staging.rglob("*")) if p.is_file()},
        }
        (staging / "build-info.json").write_text(json.dumps(manifest, indent=2) + "\n")
        if destination.exists():
            # Only an earlier directory bearing our build marker may be replaced.
            shutil.rmtree(destination)
        staging.replace(destination)
        return {"output": str(destination), "files": len(manifest["files"]) + 1,
                "bytes": sum(item["bytes"] for item in manifest["files"].values()),
                "pyodide": VERSION, "numpy": manifest["numpy_version"]}
    finally:
        if staging.exists():
            shutil.rmtree(staging)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=ROOT / "dist")
    parser.add_argument("--runtime", type=Path,
                        default=ROOT / "artifacts" / "pyodide-runtime" / VERSION / "pyodide")
    args = parser.parse_args()
    print(json.dumps(build(args.out, args.runtime.resolve()), indent=2))


if __name__ == "__main__":
    main()
